"""Render the system prompt of a few representative calls into docs/prompts/*.md, so a prompt
change shows up as a readable diff in review. `make prompts` runs it (no API calls). The date,
the settings and the candidate are frozen here, so only a change to the prompt changes the files.

Each file shows the two parts: the fixed part (identical for every call with the same settings
and flags, cached across calls) and the part that differs per call.
"""

from datetime import UTC, date, datetime, timedelta
from pathlib import Path

from hr_screener.agent.prompts import build_system_prompt_parts
from hr_screener.config import Settings
from hr_screener.models import (
    Availability,
    CallSummary,
    Candidate,
    OnboardingSlot,
    Opening,
    Outcome,
    Role,
    ScreeningFacts,
    SlotMode,
    Subject,
)
from hr_screener.screening.followup import ClosedContext, EndedHow, FollowUpContext

OUT = Path(__file__).resolve().parents[2] / "docs" / "prompts"
NOW = datetime(2026, 11, 10, 12, 0, tzinfo=UTC)

SETTINGS = Settings(
    _env_file=None,
    language="en",
    kb_language="es",
    timezone="Europe/Madrid",
    agent_name="Sofia",
    agency_name="TuTeacher",
    country="Spain",
    followup_recent_minutes=30,
)
OPENING = Opening(
    id="opening", role=Role.TUTOR, location="Madrid", subjects=[Subject.MATH, Subject.PHYSICS]
)
CANDIDATE = Candidate(
    id="candidate",
    name="Maria Lopez",
    phone="+34600000000",
    location="Madrid",
    opening_id=OPENING.id,
    subjects=[Subject.MATH],
)
SLOT = OnboardingSlot(
    id="slot",
    starts_at=datetime(2026, 11, 12, 16, 0, tzinfo=UTC),
    mode=SlotMode.IN_PERSON,
    address="Chamberí, Madrid",
)
# The earlier call was cut off after the start date and the weekly slots (no format yet).
FOLLOWUP = FollowUpContext(
    previous_screening_id="previous",
    attempt=2,
    previous_at=NOW - timedelta(days=1),
    ended=EndedHow.DROPPED,
    callback_note=None,
    summary=CallSummary(
        key_points=["Has tutored math for five years"],
        candidate_questions=["Is the pay per hour?"],
        language="en",
        source="llm",
    ),
    facts=ScreeningFacts(
        start_date=date(2026, 11, 20),
        availability=[Availability.WORKDAYS_AFTERNOON, Availability.SATURDAY_MORNING],
    ),
)
BOOKED = ClosedContext("decided", Outcome.SCHEDULED, NOW, SLOT)
REJECTED = ClosedContext("decided", Outcome.NOT_QUALIFIED, NOW, None)
# name -> (title, follow-up context, closed context)
CASES: dict[str, tuple[str, FollowUpContext | None, ClosedContext | None]] = {
    "fresh": ("A first call", None, None),
    "followup": ("A follow-up, cut off before the weekly format", FOLLOWUP, None),
    "booked": ("A candidate who is already booked", None, BOOKED),
    "rejected": ("A candidate who was rejected", None, REJECTED),
}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, (title, followup, closed) in CASES.items():
        parts = build_system_prompt_parts(
            CANDIDATE,
            OPENING,
            SETTINGS,
            now=NOW,
            followup=followup,
            closed=closed,
            knowledge=True,
            frustration_notes=True,
        )
        (OUT / f"{name}.md").write_text(
            f"# {title}\n\n"
            "Generated by `make prompts` (evals/prompts/render.py); do not edit. Date frozen at "
            "2026-11-10 12:00 UTC, monitor notes on, knowledge tools on (except for a rejected "
            "candidate, who is not offered them).\n\n"
            f"## Fixed part ({len(parts.fixed)} characters)\n\n"
            "The same for every call with these settings and flags; cached across calls.\n\n"
            f"````text\n{parts.fixed}\n````\n\n"
            f"## Per call ({len(parts.call)} characters)\n\n"
            f"````text\n{parts.call}````\n"
        )
        print(f"wrote {OUT / f'{name}.md'}")


if __name__ == "__main__":
    main()
